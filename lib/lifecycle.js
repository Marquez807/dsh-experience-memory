/** Why one record should leave the resident pool, or `undefined` to keep it. */
export function retirementReason(record              , now        )                     {
  if (record.expiresAt !== null && record.expiresAt <= now) return 'expired'
  if (record.reviewAfter !== null
    && now - record.reviewAfter > REVIEW_GRACE_DAYS * DAY
    && record.reuseCount === 0
    && record.successCount === 0) {
    return 'review overdue and never reused'
  }
  const anchor = record.lastUsedAt ?? record.createdAt
  const aged = now - anchor > STALE_DAYS * DAY
  if (aged && record.reuseCount === 0) {
    const score = importance({
      evidence: record.evidence,
      successCount: record.successCount,
      reuseCount: record.reuseCount,
      failStreak: record.failStreak,
      distinctWorkspaces: record.distinctWorkspaces,
      createdAt: record.createdAt,
      lastUsedAt: record.lastUsedAt,
      reviewAfter: record.reviewAfter,
      now,
    })
    if (score < RETIRE_FLOOR) return 'never reused and below the retire floor'
  }
  return undefined
}

/**
 * Marker written into `needsReview` when a record's cited file is no longer on disk.
 *
 * Prefixed so the symmetric case can clear exactly this flag and not a human's note.
 */
export const SOURCE_GONE = '出处文件已不存在：'

/**
 * Flag `verified-file` records whose cited file is no longer there.
 *
 * The evidence grade proves the quoted passage is *in* a file at the moment the record is
 * written. It does not promise the file will still exist in a week — files get renamed, moved,
 * cleaned up. And when it is gone the record becomes actively harmful: a real model reading it
 * back asks where the cited file is, fails to find it, and throws the whole record away rather
 * than trust a citation it cannot follow (measured; see `docs/DELIVERY-GAPS.md` §17).
 *
 * So maintenance checks the file, and flags rather than blocks: a cited file may legitimately
 * not exist *yet* (a record about something the lesson precedes) or may come back from a
 * restore. The flag is a note to a reader, not a downgrade — the record stays confirmed and
 * deliverable until someone looks at it.
 *
 * Runs over the same bounded, cursor-resumed batch the rest of maintenance scans, so a large
 * store never pays a full table walk. `workspaceRoot` is required to resolve the record's
 * workspace-relative path; without it nothing is checked, because guessing a root would flag
 * every record or none.
 */
export function checkProvenance(
  db              ,
  records                         ,
  workspaceRoot        ,
)         {
  if (workspaceRoot.trim() === '') return 0
  let flagged = 0
  for (const record of records) {
    if (record.evidence !== 'verified-file') continue
    const ref = String(record.sourceRef ?? '').trim()
    if (ref === '' || /^call_/i.test(ref)) continue
    // An absolute path cannot be resolved against the workspace and cannot be checked here;
    // it was not verifiable when the record was written either.
    if (isAbsolute(ref)) continue
    // Strip a trailing `:line` / `:line:col`, keeping any Windows drive colon out of the way
    // (a relative path has none).
    const path = ref.replace(/:\d+(?::\d+)?$/, '')
    if (path === '') continue
    const already = record.needsReview !== null && String(record.needsReview).startsWith(SOURCE_GONE)
    const exists = existsSync(join(workspaceRoot, path))
    if (!exists && !already) {
      upsert(db, { ...record, needsReview: `${SOURCE_GONE}${path}` })
      flagged += 1
    } else if (exists && already) {
      // The file came back (a restore, an un-delete). Clear the note rather than let a stale
      // warning outlive its own cause.
      upsert(db, { ...record, needsReview: null })
    }
  }
  return flagged
}

/**
 * One bounded maintenance pass: age out what nothing is using.
 *
 * Runs at turn end and never on the retrieval path, so a large store cannot
 * slow a search down. The scan resumes from a cursor and wraps, so repeated
 * passes cover everything without walking the whole table at once.
 */
export function maintain(db              , input               )                 {
  const batchSize = Math.max(1, Math.trunc(input.batchSize))
  const cursor = readMeta(db, CURSOR_KEY)
  let batch = confirmedAfter(db, cursor, batchSize)
  let wrapped = false
  if (batch.length === 0 && cursor !== '') {
    batch = confirmedAfter(db, '', batchSize)
    wrapped = true
  }

  // Provenance first: it does not retire anything, and a record that is about to be aged out
  // for never being used should still have its flag say why a reader distrusted it.
  const provenanceFlags = input.workspaceRoot === undefined
    ? 0
    : checkProvenance(db, batch, input.workspaceRoot)

  const reasons                         = {}
  let retired = 0
  for (const record of batch) {
    const reason = retirementReason(record, input.now)
    if (reason === undefined) continue
    forget(db, { recordId: record.id, reason: `maintenance: ${reason}`, actor: 'experience-memory', now: input.now })
    reasons[reason] = (reasons[reason] ?? 0) + 1
    retired += 1
  }

  const last = batch[batch.length - 1]
  if (last !== undefined) writeMeta(db, CURSOR_KEY, last.id)
  else writeMeta(db, CURSOR_KEY, '')

  // Stores written before `deleteRecord` learned to clean up after a purge still carry
  // the rows that would mis-count a future corroboration, so the sweep runs here too and
  // repairs them rather than waiting for the next purge of the same content.
  const orphanCorroborations = pruneCorroboration(db)

  // Candidates are swept here because nothing else sweeps them: the scan above only
  // reaches confirmed records, so without this a candidate is immortal.
  const candidates = sweepCandidates(
    db,
    input.now,
    input.candidateTtlDays ?? CANDIDATE_TTL_DAYS_DEFAULT,
    input.candidatePoolLimit ?? CANDIDATE_POOL_DEFAULT,
  )

  // Last, and best effort: fold the log back into the main file so the store is not one
  // file that is current plus one that carries everything recent.
  checkpointWal(db)

  return {
    scanned: batch.length,
    retired,
    reasons,
    orphanCorroborations,
    candidatesAged: candidates.aged,
    candidatesEvicted: candidates.evicted,
    provenanceFlags,
  }
}
